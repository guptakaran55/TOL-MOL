package com.signalscope.app.network

import android.content.Context
import android.util.Log
import com.google.gson.Gson
import com.signalscope.app.data.ConfigManager
import okhttp3.OkHttpClient
import okhttp3.Request
import java.io.File
import java.util.concurrent.TimeUnit

/**
 * TRADING SYMBOL → INSTRUMENT TOKEN, for the Kite streaming socket.
 *
 * The REST endpoints take a readable "NSE:RELIANCE". The streaming socket does
 * not: it speaks only in numeric instrument tokens, and there is no lookup call
 * — the mapping arrives exactly one way, as a full CSV dump of every tradable
 * instrument on the exchange (tens of thousands of rows, several megabytes).
 *
 * So this exists purely to make the socket usable. It downloads the dump, keeps
 * the NSE equity rows, and caches the mapping on disk.
 *
 * WHY IT IS CACHED FOR A DAY. The dump is regenerated by Zerodha each morning
 * and is stable within a session; re-downloading megabytes on every reconnect
 * would be the single most expensive thing the app does, for a mapping that has
 * not changed. A day-old token is not a risk: instrument tokens are permanent
 * for a listed name, and a symbol that appears mid-day cannot be traded by an
 * algo whose universe was fixed before the open anyway.
 *
 * WHY FAILURE IS SOFT. If the dump cannot be fetched the app must not lose its
 * price feed — it falls back to whatever was cached, and if there is no cache,
 * the caller is told and stays on Yahoo. A broken mapping should cost you the
 * Zerodha experiment, never the prices your positions are marked against.
 */
object ZerodhaInstruments {

    private const val TAG = "ZerodhaInstruments"
    private const val URL = "https://api.kite.trade/instruments"
    private const val CACHE_FILE = "kite_instruments_nse_v1.json"
    private const val MAX_AGE_MS = 20L * 60L * 60L * 1000L   // ~a trading day

    private val gson = Gson()

    private data class Cache(
        val fetchedAt: Long = 0L,
        val bySymbol: Map<String, Long> = emptyMap()
    )

    @Volatile private var memo: Cache? = null

    private val http = OkHttpClient.Builder()
        .connectTimeout(30, TimeUnit.SECONDS)
        .readTimeout(90, TimeUnit.SECONDS)   // multi-MB CSV
        .retryOnConnectionFailure(true)
        .build()

    private fun file(ctx: Context) = File(ctx.filesDir, CACHE_FILE)

    private fun loadDisk(ctx: Context): Cache? = try {
        val f = file(ctx)
        if (!f.exists()) null else gson.fromJson(f.readText(), Cache::class.java)
    } catch (e: Exception) { Log.w(TAG, "cache read failed: ${e.message}"); null }

    private fun saveDisk(ctx: Context, c: Cache) {
        try {
            val f = file(ctx)
            val tmp = File(f.parentFile, f.name + ".tmp")
            tmp.writeText(gson.toJson(c))
            if (f.exists()) f.delete()
            tmp.renameTo(f)
        } catch (e: Exception) { Log.e(TAG, "cache write failed", e) }
    }

    /** Token for one NSE equity trading symbol, or null if unknown. */
    fun tokenFor(ctx: Context, config: ConfigManager, tradingSymbol: String): Long? =
        map(ctx, config)[tradingSymbol.trim().uppercase()]

    /**
     * The whole NSE-equity mapping. Network call on a cold or stale cache —
     * never call from the main thread.
     */
    @Synchronized
    fun map(ctx: Context, config: ConfigManager): Map<String, Long> {
        val now = System.currentTimeMillis()
        memo?.let { if (now - it.fetchedAt < MAX_AGE_MS && it.bySymbol.isNotEmpty()) return it.bySymbol }
        loadDisk(ctx)?.let {
            memo = it
            if (now - it.fetchedAt < MAX_AGE_MS && it.bySymbol.isNotEmpty()) return it.bySymbol
        }

        val fresh = download(config)
        if (fresh.isNotEmpty()) {
            val c = Cache(now, fresh)
            memo = c
            saveDisk(ctx, c)
            Log.i(TAG, "instrument map refreshed — ${fresh.size} NSE equities")
            return fresh
        }
        // Stale beats nothing: an old mapping still resolves every listed name.
        val fallback = memo?.bySymbol ?: emptyMap()
        if (fallback.isEmpty()) Log.w(TAG, "no instrument map available — caller must stay on Yahoo")
        else Log.w(TAG, "instrument refresh failed — using ${fallback.size} cached tokens")
        return fallback
    }

    private fun download(config: ConfigManager): Map<String, Long> {
        if (!config.isZerodhaConnected) return emptyMap()
        return try {
            val req = Request.Builder()
                .url(URL)
                .addHeader("X-Kite-Version", "3")
                .addHeader("Authorization",
                    "token ${config.zerodhaApiKey}:${config.zerodhaAccessToken}")
                .get().build()
            http.newCall(req).execute().use { resp ->
                if (!resp.isSuccessful) {
                    Log.w(TAG, "instruments HTTP ${resp.code}")
                    return emptyMap()
                }
                parseCsv(resp.body?.charStream()?.buffered()?.readLines() ?: emptyList())
            }
        } catch (e: Exception) {
            Log.w(TAG, "instruments fetch failed: ${e.message}"); emptyMap()
        }
    }

    /**
     * Columns are read BY NAME from the header row rather than by position.
     * Kite has added columns to this dump before, and a positional parser would
     * not fail — it would silently map symbols to the wrong tokens, which shows
     * up as the price of one company appearing under another's name.
     */
    private fun parseCsv(lines: List<String>): Map<String, Long> {
        if (lines.size < 2) return emptyMap()
        val head = lines.first().split(",").map { it.trim().trim('"') }
        val iTok = head.indexOf("instrument_token")
        val iSym = head.indexOf("tradingsymbol")
        val iType = head.indexOf("instrument_type")
        val iExch = head.indexOf("exchange")
        if (iTok < 0 || iSym < 0 || iExch < 0) {
            Log.e(TAG, "instrument dump header not recognised: $head")
            return emptyMap()
        }
        val out = HashMap<String, Long>(4096)
        for (i in 1 until lines.size) {
            val row = lines[i]
            if (row.isBlank()) continue
            val c = row.split(",")
            if (c.size <= maxOf(iTok, iSym, iExch)) continue
            if (!c[iExch].trim().trim('"').equals("NSE", true)) continue
            if (iType >= 0 && c.size > iType &&
                !c[iType].trim().trim('"').equals("EQ", true)) continue
            val sym = c[iSym].trim().trim('"').uppercase()
            val tok = c[iTok].trim().trim('"').toLongOrNull() ?: continue
            if (sym.isNotEmpty()) out[sym] = tok
        }
        return out
    }
}
